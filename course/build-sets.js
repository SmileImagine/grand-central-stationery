#!/usr/bin/env node
// Writes course/sets.js: every set the library and the board read, as one script,
// so a page opened from disk (file:) can show them. A browser will not let a page
// opened from disk fetch the JSON beside it, but it will run a script tag.
//
//   node course/build-sets.js            write sets.js
//   node course/build-sets.js --check    exit 1 when sets.js is stale (the smoke test runs this)
//
// Served pages still fetch the JSON first and fall back to this file only when that fails,
// so the JSON stays the source of truth and this file is a copy to regenerate after
// any set or workshop item changes (the Makefile's `make sets` does it).
const fs = require('fs'), path = require('path');
const root = __dirname, out = path.join(root, 'sets.js');
const read = f => { const p = path.join(root, f); return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : null; };
const sets = { tunes: read('set.json'), rhythms: read('rhythm-set.json'), dances: read('dance-set.json'), figures: read('figure-set.json'), holding: read('holding/index.json'), review: read('review/index.json'), sketches: {} };
if (sets.holding) for (const it of sets.holding.items) {
  const p = path.join(root, 'holding', it.file);
  if (fs.existsSync(p)) sets.sketches[it.id] = fs.readFileSync(p, 'utf8');
}
const text = '// Generated by course/build-sets.js from the JSON sets beside it; do not edit. Regenerate with: node course/build-sets.js\n'
  + 'window.GCS_SETS = ' + JSON.stringify(sets) + ';\n';
if (process.argv.includes('--check')) {
  const old = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (old !== text) { console.error('course/sets.js is stale; run node course/build-sets.js'); process.exit(1); }
  console.log(`course/sets.js is current (${(text.length / 1024).toFixed(0)} kB)`);
} else {
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${(text.length / 1024).toFixed(0)} kB; ${Object.keys(sets.sketches).length} sketches embedded)`);
}
